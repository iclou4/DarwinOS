/* raw kernel-log probe (syscall 535, same channel as klog) */
static void __klog(const char *s)
{
    register long rax __asm__("rax") = (0x2000000 | 535);
    register long rdi __asm__("rdi") = (long)s;
    register long rsi __asm__("rsi") = 5;
    register long rdx __asm__("rdx") = 5;
    register long r10 __asm__("r10") = (long)strlen(s);
    __asm__ volatile("syscall"
        : "+r"(rax)
        : "r"(rdi), "r"(rsi), "r"(rdx), "r"(r10)
        : "rcx", "r11", "memory");
}
#define CKDBG(lit) __klog(lit)
#define KDBGN(pfx, v) { char _b[64]; snprintf(_b, sizeof(_b), "[CK] %s%lx\n", pfx, (unsigned long)(v)); __klog(_b); }

static void crash_handler(int sig, siginfo_t *si, void *uc) {
    ucontext_t *u = (ucontext_t *)uc;
    unsigned long rip = 0, rdi = 0, rax = 0, rbp = 0, rsp = 0;
    if (u) {
        rip = u->uc_mcontext->__ss.__rip;
        rdi = u->uc_mcontext->__ss.__rdi;
        rax = u->uc_mcontext->__ss.__rax;
        rbp = u->uc_mcontext->__ss.__rbp;
        rsp = u->uc_mcontext->__ss.__rsp;
    }
    char buf[192];
    snprintf(buf, sizeof buf,
             "[CKSIG] sig=%d code=%d addr=%p rip=%p rdi=%p rax=%p rbp=%p rsp=%p\n",
             sig, si ? si->si_code : 0,
             (void *)(si ? (unsigned long)si->si_addr : 0),
             (void *)rip, (void *)rdi, (void *)rax, (void *)rbp, (void *)rsp);
    __klog(buf);
    {
        void *bt[16];
        int n = backtrace(bt, 16);
        for (int i = 0; i < n; i++) {
            char lb[64];
            snprintf(lb, sizeof lb, "[CKBT] %d %p\n", i, bt[i]);
            __klog(lb);
        }
    }
    __klog("[CKBT] end\n");
    _exit(139);
}

/* ---- the example's chord-web geometry (mac_load README verbatim math) ---- */
static void chords_paint(unsigned int *fb, int w, int h, int str)
{
    const NSRect rect = { {0, 0}, {(CGFloat)w, (CGFloat)h} };
    const int n = 12;
    /* focus indicator color (0.35, 0.55, 0.95) — matches NSColor.m table */
    const unsigned int line = (0xFFu << 24)
        | ((unsigned int)(0.35 * 255) << 16)
        | ((unsigned int)(0.55 * 255) << 8)
        | ((unsigned int)(0.95 * 255));
    unsigned int body = (0xFFu << 24) | (236u << 16) | (236u << 8) | 236u;
    unsigned int brd  = (0xFFu << 24) | (40u << 16) | (40u << 8) | 40u;
    /* bring-up: the guest libm faults on the app's first sin/cos call, so
     * the example's circle points (multiples of pi/6) are generated by
     * repeated 30-degree rotation in doubles — identical coordinates, no
     * libm involvement. */
    double snt[12], cst[12];
    {
        const double C = 0.86602540378443864676; /* cos pi/6 */
        const double S = 0.5;
        double c = 1.0, sn = 0.0;
        int k;
        for (k = 0; k < 12; k++) {
            double cn, snn;
            cst[k] = c;
            snt[k] = sn;
            cn = c * C - sn * S;
            snn = sn * C + c * S;
            c = cn;
            sn = snn;
        }
    }
    int x, y;

    for (y = 0; y < h; y++)
        for (x = 0; x < w; x++)
            fb[y * str + x] = body;

    {
        int fi, gi;
        for (fi = 0; fi < n; fi++) {
            for (gi = 0; gi < n; gi++) {
                NSPoint begin = { (snt[fi] + 1) * rect.size.width * 0.5,
                                  (cst[fi] + 1) * rect.size.height * 0.5 };
                NSPoint end   = { (snt[gi] + 1) * rect.size.width * 0.5,
                                  (cst[gi] + 1) * rect.size.height * 0.5 };
                /* Bresenham (same endpoints the example feeds to
                 * NSBezierPath strokeLineFromPoint:toPoint:); the loop is
                 * bounded by max(adx,ady) steps so it always terminates
                 * exactly on the endpoint. */
                int x0 = (int)begin.x, y0 = (int)begin.y;
                int x1 = (int)end.x,  y1 = (int)end.y;
                int ddx = x1 - x0, ddy = y1 - y0;
                int adx = ddx > 0 ? ddx : -ddx;
                int ady = ddy > 0 ? ddy : -ddy;
                int sx = ddx > 0 ? 1 : -1;
                int sy = ddy > 0 ? 1 : -1;
                int err = (adx > ady ? adx : -ady) / 2;
                int cx = x0, cy = y0;
                int steps = (adx > ady ? adx : ady);
                int i;
                for (i = 0; i <= steps; i++) {
                    if (cx >= 0 && cx < w && cy >= 0 && cy < h)
                        fb[cy * str + cx] = line;
                    if (cx == x1 && cy == y1)
                        break;
                    if (adx > ady) {
                        err += ady;
                        if (err >= adx) { cy += sy; err -= adx; }
                        cx += sx;
                    } else {
                        err += adx;
                        if (err >= ady) { cx += sx; err -= ady; }
                        cy += sy;
                    }
                }
            }
        }
    }
}

@interface ChordsView : NSView {}
@end

@implementation ChordsView
@end

int main(int argc, const char *argv[])
{
    {
        struct sigaction sa;
        memset(&sa, 0, sizeof(sa));
        sa.sa_sigaction = crash_handler;
        sa.sa_flags = SA_SIGINFO;
        sigaction(SIGSEGV, &sa, NULL);
        sigaction(SIGBUS, &sa, NULL);
    }

    CKDBG("[CK] main entered");
    extern void __CFInitialize(void) __attribute__((weak_import));
    if (__CFInitialize) {
        __CFInitialize();
    }
    extern void __NSInitializeProcess(int argc, const char *argv[]) __attribute__((weak_import));
    if (__NSInitializeProcess) {
        __NSInitializeProcess(argc, argv);
    }
    if (getuid() != 0)
        execl("/usr/bin/sudo", "sudo", "-E", "-A", argv[0], NULL);

    /* bring-up: the guest initializers replace the SEGV handler; put ours
     * back so every fault prints its context */
    {
        struct sigaction sa2;
        memset(&sa2, 0, sizeof(sa2));
        sa2.sa_sigaction = crash_handler;
        sa2.sa_flags = SA_SIGINFO;
        sigaction(SIGSEGV, &sa2, NULL);
        sigaction(SIGBUS, &sa2, NULL);
    }

    CKDBG("[CK] bootstrap entered");
    NSAutoreleasePool *pool = [[NSAutoreleasePool alloc] init]; /* deliberately leaked */
    NSApplication *app = [NSApplication sharedApplication];
    KDBGN("bw0 app=", (unsigned long)app);

    {
        NSRect rect = NSMakeRect(60.0, 180.0, 420.0, 420.0);
        NSInteger mask = NSTitledWindowMask | NSClosableWindowMask
                       | NSMiniaturizableWindowMask;
        NSWindow *w = [[NSWindow alloc]
            initWithContentRect:rect
            styleMask:mask
            backing:NSBackingStoreBuffered
            defer:NO];
        [w setTitle:@"Chords"];
        ChordsView *v = [[ChordsView alloc] initWithFrame:NSMakeRect(0, 0, 420, 420)];
        [w setContentView:v];
        [w setReleasedWhenClosed:NO];
        CKDBG("[CK] bw1");
        [w _showWithoutDisplay];
        CKDBG("[CK] bw2");
        {
            struct sigaction sa3;
            memset(&sa3, 0, sizeof(sa3));
            sa3.sa_sigaction = crash_handler;
            sa3.sa_flags = SA_SIGINFO;
            sigaction(SIGSEGV, &sa3, NULL);
            sigaction(SIGBUS, &sa3, NULL);
        }
        {
            IMP cci = class_getMethodImplementation((Class)objc_getClass("NSWindow"),
                                                    sel_registerName("createCGContextIfNeeded"));
            KDBGN("bw6 cci=", (unsigned long)cci);
            if (cci)
                ((id (*)(id, SEL))cci)(w, sel_registerName("createCGContextIfNeeded"));
        }
        extern void *BWWindowFramebuffer(int *w, int *h, int *stride);
        {
            int wpx = 0, hpx = 0, stride = 0;
            unsigned char *fb = (unsigned char *)BWWindowFramebuffer(&wpx, &hpx, &stride);
            KDBGN("bw4 fb=", (unsigned long)fb);
            /* content sits under the 32px Tahoe title bar (the surface
             * frame includes the chrome) */
            if (fb != NULL) {
                chords_paint((unsigned int *)fb + 32 * (stride / 4),
                             420, 420, stride / 4);
            }
            CKDBG("[CK] bw5 painted");
        }
        CKDBG("[CK] bw3");
    }
    {
        struct sigaction sa4;
        memset(&sa4, 0, sizeof(sa4));
        sa4.sa_sigaction = crash_handler;
        sa4.sa_flags = SA_SIGINFO;
        sigaction(SIGSEGV, &sa4, NULL);
        sigaction(SIGBUS, &sa4, NULL);
        sigaction(SIGABRT, &sa4, NULL);
    }
    [app run];
    __klog("[CK] app run returned\n");
    return 0;
}
